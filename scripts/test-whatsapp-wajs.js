const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const target = path.join(__dirname, '../chrome-extension/whatsapp-sync/wa-page.js');
assert.ok(fs.existsSync(target), 'WA-JS read-only adapter must exist');
const { readSnapshot } = require(target);
function fixture() {
  const wid = value => ({ _serialized:value, user:value.split('@')[0], server:value.split('@')[1] });
  const state = { me:wid('15550001111@c.us'), chat:{ id:wid('15551234567@c.us'), formattedTitle:'Alice', msgs:{ getModelsArray:() => state.models } }, models:[] };
  const msg = (remote, suffix, type='chat', text='Hello', fromMe=false) => ({ id:{ _serialized:`${fromMe}_${remote}_${suffix}`, remote:wid(remote), fromMe }, type, body:text, t:1700000000 });
  state.models = [msg('15551234567@c.us','A'), msg('15551234567@c.us','B','image','',true), msg('19999999999@c.us','OTHER')];
  const forbid = () => { throw Error('write operation invoked'); };
  const wpp = { isReady:true, conn:{ isAuthenticated:() => true, getMyUserId:() => state.me }, chat:{ getActiveChat:() => state.chat, sendTextMessage:forbid, markIsRead:forbid }, contact:{ getPnLidEntry:async () => ({}) } };
  return { state, wpp, wid, msg };
}
(async () => {
  const { state, wpp, wid, msg } = fixture();
  let result = await readSnapshot(wpp);
  assert.equal(result.accountId, '15550001111@c.us');
  assert.equal(result.phone, '+15551234567');
  assert.equal(result.source, 'WA-JS');
  assert.equal(result.messages.length, 2, 'foreign conversation messages excluded');
  assert.equal(result.messages[0].timestamp, '2023-11-14T22:13:20.000Z');
  assert.equal(result.messages[1].direction, 'out');
  assert.equal(result.messages[1].kind, 'image');
  state.models = [msg('15551234567@c.us','X','chat','<img src=x>')];
  assert.equal((await readSnapshot(wpp)).messages[0].text, '<img src=x>', 'preserve text without interpreting HTML');
  state.models = [msg('15551234567@c.us','LONG','chat','中'.repeat(20001))];
  result = await readSnapshot(wpp);
  assert.equal(result.ok, false, 'overlong text must fail visibly, never acknowledge truncated content');
  assert.match(result.message, /20000/);
  state.models = [{ ...msg('15551234567@c.us','CAPTION','image'), caption:'x'.repeat(20001) }];
  assert.equal((await readSnapshot(wpp)).ok, false, 'overlong media caption must also fail visibly');
  state.chat.id = wid('999999999999999@lid'); state.models=[];
  result = await readSnapshot(wpp);
  assert.equal(result.phone, '', 'LID is not a phone number');
  wpp.contact.getPnLidEntry = async () => ({ phoneNumber:{ id:'15551234567', server:'c.us', _serialized:'15551234567@c.us' } });
  assert.equal((await readSnapshot(wpp)).phone, '+15551234567');
  wpp.contact.getPnLidEntry = async () => { state.me=wid('15550002222@c.us'); return {}; };
  assert.equal((await readSnapshot(wpp)).ok, false, 'account changed while mapping must invalidate snapshot');
  wpp.contact.getPnLidEntry = async () => { state.chat.id=wid('123456789@g.us'); return {}; };
  assert.equal((await readSnapshot(wpp)).ok, false, 'chat changed while mapping must invalidate snapshot');
  assert.equal((await readSnapshot(wpp)).ok, false, 'group excluded');
  assert.equal((await readSnapshot({})).ok, false, 'library not ready fails closed');
  const fresh=fixture(); fresh.wpp.conn.isAuthenticated=()=>false;
  assert.equal((await readSnapshot(fresh.wpp)).ok, false, 'signed-out account fails closed');
  fresh.wpp.conn.isAuthenticated=()=>true; fresh.state.models=Array(2001).fill(fresh.msg('15551234567@c.us','A'));
  assert.equal((await readSnapshot(fresh.wpp)).ok, false, 'oversize snapshots fail visibly instead of silently truncating');
  console.log('WA-JS reader passed: identity, LID mapping, foreign-message filtering, timestamps, account/chat races, fail-closed readiness.');
})().catch(error => { console.error(error); process.exitCode=1; });
