const assert = require('node:assert/strict');
const { DatabaseSync } = require('node:sqlite');
const { createWhatsAppStore } = require('../mac-app/whatsapp-store');
const db = new DatabaseSync(':memory:');
db.exec('CREATE TABLE customers(name TEXT PRIMARY KEY, data_json TEXT NOT NULL)');
const add = (name, phones) => db.prepare('INSERT INTO customers VALUES(?, ?)').run(name, JSON.stringify({ phones }));
add('Alice', ['+1 (202) 555-0127', '+44 7700 900127']);
add('Bob', ['+1 2025550128']);
const store = createWhatsAppStore(db);
assert.equal(store.search({ phone:'+1 2025550127' }).customers[0].name, 'Alice');
assert.equal(store.search({ phone:'5550127' }).customers.length, 0);
add('Duplicate', ['+1 2025550127']);
assert.equal(store.search({ phone:'+1 2025550127' }).customers.length, 2);
assert.equal(store.search({ query:'Alice' }).customers[0].name, 'Alice');
const conversation = { account:'Business A', chatId:'12025550128@c.us', title:'Bob' };
const message = { id:'m1', text:'Hello <script>doNotRun()</script>', direction:'in', timestamp:'[10:20, 21/09/2026]', kind:'text' };
assert.throws(() => store.sync({ ...conversation, messages:[message] }), /关联/);
assert.throws(() => store.bind({ ...conversation, customer:'Missing' }), /客户/);
store.bind({ ...conversation, customer:'Bob' });
assert.equal(store.sync({ ...conversation, messages:[message] }).inserted, 1);
assert.equal(store.sync({ ...conversation, messages:[message] }).inserted, 0);
assert.throws(() => store.bind({ ...conversation, customer:'Alice' }), /关联/);
assert.equal(store.messages({ customer:'Bob' }).messages[0].text, message.text);
assert.equal(store.messages({ customer:'Alice' }).messages.length, 0);
assert.throws(() => store.sync({ ...conversation, chatId:'123@g.us', messages:[message] }), /群聊/);
assert.throws(() => store.sync({ ...conversation, account:'Business B', messages:[message] }), /关联/);
store.bind({ ...conversation, account:'Business B', customer:'Alice' });
assert.equal(store.sync({ ...conversation, account:'Business B', messages:[message] }).inserted, 1);
assert.equal(store.messages({ customer:'Alice' }).total, 1);
assert.throws(() => store.sync({ ...conversation, messages:[{ ...message, id:'bad', direction:'invalid' }] }), /方向/);
assert.equal(store.messages({ customer:'Bob' }).total, 1, 'invalid batch must not partially write');
for (let i = 2; i <= 55; i++) store.sync({ ...conversation, messages:[{ ...message, id:`m${i}` }] });
const first = store.messages({ customer:'Bob', limit:20 });
const second = store.messages({ customer:'Bob', limit:20, before:first.nextBefore });
assert.equal(first.messages.length, 20);
assert.equal(second.messages.length, 20);
assert.equal(first.messages.some(a => second.messages.some(b => a.id === b.id)), false);
assert.equal(first.total, 55);
store.sync({ ...conversation, messages:[{ id:'hydration', direction:'in', kind:'other', text:'', timestamp:'' }] });
const enriched = store.sync({ ...conversation, messages:[{ id:'hydration', direction:'in', kind:'text', text:'Now loaded', timestamp:'[10:30, 21/09/2026]' }] });
assert.equal(enriched.inserted, 0);
assert.equal(enriched.updated, 1, 'late-loading message content must fill empty capture');
assert.equal(store.messages({ customer:'Bob' }).messages[0].text, 'Now loaded');
db.close();
console.log('WhatsApp store: exact phone, ambiguity, explicit binding, deduplication, isolation and pagination passed.');
